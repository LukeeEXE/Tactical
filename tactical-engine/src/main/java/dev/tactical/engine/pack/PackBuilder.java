    /**
     * HUD and chat glyphs (original pixel art, see {@link HudGlyphs}) in three fonts with their own vertical
     * placement: {@code tactical:hud_chat}, {@code tactical:hud_bossbar}, {@code tactical:hud_money}. Textures live
     * at {@code assets/tactical/textures/hud/<name>.png}, so an admin PNG at that path replaces the art.
     * Also restyles the YELLOW boss bar as a thin progress line and makes the WHITE boss bar invisible (the match HUD
     * uses these two colours; nothing else on the server does).
     */
    private void generateHud(Map<String, byte[]> files) {
        Map<String, com.google.gson.JsonArray> providers = new java.util.TreeMap<>();
        for (HudGlyphs.Glyph g : HudGlyphs.all()) {
            files.put("assets/tactical/textures/hud/" + g.name() + ".png", HudGlyphs.png(g.image()));
            // Chat and boss-bar icons render at letter height (8 px) whatever the source size (8x8 or 16x16).
            int height = switch (g.slot()) {
                case CHAT -> g.height() > 8 ? HudGlyphs.CHAT_ICON_HEIGHT : 8; // large icons: as tall as capitals
                case BAR_ICON, MONEY_ICON -> 8;
                case BAR_BOMB -> 32;             // 16x16 icon drawn at 32 px (crisp 2x)
                default -> g.height();
            };
            int ascent = switch (g.slot()) {
                case CHAT -> 7;
                case BAR_ICON -> 8;                          // same rows as an inline player head (-1..6)
                case BAR_TIME -> 7 - hud.bossbarTimeRow();
                case BAR_BOMB -> 7;
                case PLANT_BAR -> 6;
                case TOOLTIP_TAG -> 7;                       // rows 0..8 of a lore line: 2 px around Pinch capitals                         // rows 1..7: centred in the 13 px box (rows -2..10)
                case BAR_STRIP -> hud.bossbarTileAscent();
                case BAR_PANEL -> hud.bossbarPanelAscent();
                case BAR_SCORE -> hud.bossbarScoreAscent();
                case MONEY_PANEL -> 7 - (hud.moneyOffsetY() - 2);
                case MONEY_ICON -> 7 - hud.moneyOffsetY();
                case ACTION_PANEL -> hud.actionPanelAscent();
            };
            String font = switch (g.slot()) {
                case CHAT -> "hud_chat";
                case BAR_STRIP, BAR_ICON, BAR_PANEL, BAR_SCORE, BAR_TIME, BAR_BOMB -> "hud_bossbar";
                case MONEY_PANEL, MONEY_ICON -> "hud_money";
                case ACTION_PANEL, PLANT_BAR -> "hud_actionbar";
                case TOOLTIP_TAG -> "hud_tooltip";
            };
            JsonObject p = new JsonObject();
            p.addProperty("type", "bitmap");
            p.addProperty("file", "tactical:hud/" + g.name() + ".png");
            p.addProperty("ascent", Math.min(ascent, height));
            p.addProperty("height", height);
            com.google.gson.JsonArray chars = new com.google.gson.JsonArray();
            chars.add(String.valueOf(g.ch()));
            p.add("chars", chars);
            providers.computeIfAbsent(font, k -> new com.google.gson.JsonArray()).add(p);
        }
        for (Map.Entry<String, com.google.gson.JsonArray> e : providers.entrySet()) {
            JsonObject font = new JsonObject();
            font.add("providers", e.getValue());
            files.put("assets/tactical/font/" + e.getKey() + ".json", json(font));
        }
        byte[] invisible = HudGlyphs.png(HudGlyphs.bossBarInvisible());
        files.put("assets/minecraft/textures/gui/sprites/boss_bar/white_background.png", invisible);
        files.put("assets/minecraft/textures/gui/sprites/boss_bar/white_progress.png", invisible);
    }

