    private void generateBlocks(List<CustomBlock> blocks, Set<String> knownBlocks, Map<String, byte[]> user,
                                Map<String, byte[]> out, List<PackIssue> issues) {
        Map<String, CustomBlock> claimed = new LinkedHashMap<>();
        Map<String, Map<String, CustomBlock>> glazed = new TreeMap<>();
        Map<String, CustomBlock> rotating = new TreeMap<>();
        Map<String, CustomBlock> slabs = new TreeMap<>();
        for (CustomBlock b : blocks) {
            String where = "blocks/" + b.id();
            if (!knownBlocks.contains(b.blockId())) {
                issues.add(new PackIssue(true, where, "minecraft:" + b.blockId() + " does not exist on this server version"));
                continue;
            }
            CustomBlock other = claimed.putIfAbsent(b.stateKey(), b);
            if (other != null) {
                issues.add(new PackIssue(true, where, "state " + b.stateKey() + " is already used by '" + other.id() + "'"));
                continue;
            }
            if (b.kind() == CustomBlock.Kind.GLAZED_ROTATING && glazed.containsKey(b.blockId())
                    || b.kind() == CustomBlock.Kind.GLAZED_FACING && rotating.containsKey(b.blockId())) {
                issues.add(new PackIssue(true, where, b.blockId() + " cannot mix a rotating replacement with per-facing blocks"));
                continue;
            }
            // model
            if (b.model() != null) {
                String path = "assets/tactical/models/" + b.model();
                if (!user.containsKey(path)) {
                    issues.add(new PackIssue(true, where, "model file not found: resourcepack/" + path));
                    continue;
                }
                if (!b.model().equals("block/" + b.id() + ".json")) {
                    // copy under the canonical name so the blockstate can reference tactical:block/<id>
                    out.put("assets/tactical/models/block/" + b.id() + ".json", user.get(path));
                }
            } else {
                String tex = "assets/tactical/textures/" + b.texture();
                if (!user.containsKey(tex)) {
                    issues.add(new PackIssue(true, where, "texture not found: resourcepack/" + tex));
                    continue;
                }
                String texRef = "tactical:" + b.texture().substring(0, b.texture().length() - 4);
                JsonObject model = new JsonObject();
                JsonObject textures = new JsonObject();
                if (b.kind() == CustomBlock.Kind.GLAZED_ROTATING) {
                    model.addProperty("parent", "minecraft:block/template_glazed_terracotta");
                    textures.addProperty("pattern", texRef);
                } else {
                    model.addProperty("parent", "minecraft:block/cube_all");
                    textures.addProperty("all", texRef);
                }
                model.add("textures", textures);
                out.put("assets/tactical/models/block/" + b.id() + ".json", json(model));
            }
            switch (b.kind()) {
                case DOUBLE_SLAB -> slabs.put(b.blockId(), b);
                case GLAZED_FACING -> glazed.computeIfAbsent(b.blockId(), k -> new TreeMap<>()).put(b.facing(), b);
                case GLAZED_ROTATING -> rotating.put(b.blockId(), b);
            }
        }
        for (CustomBlock b : slabs.values()) {
            JsonObject variants = new JsonObject();
            variants.add("type=bottom", variant(SlabModels.bottom(b.blockId()), 0));
            variants.add("type=top", variant(SlabModels.top(b.blockId()), 0));
            variants.add("type=double", variant(b.modelRef(), 0));
            out.put("assets/minecraft/blockstates/" + b.blockId() + ".json", json(wrap(variants)));
        }
        for (Map.Entry<String, Map<String, CustomBlock>> e : glazed.entrySet()) {
            JsonObject variants = new JsonObject();
            String vanilla = "minecraft:block/" + e.getKey();
            for (String facing : CustomBlock.FACINGS) {
                CustomBlock b = e.getValue().get(facing);
                variants.add("facing=" + facing, b != null ? variant(b.modelRef(), 0) : variant(vanilla, glazedRotation(facing)));
            }
            out.put("assets/minecraft/blockstates/" + e.getKey() + ".json", json(wrap(variants)));
        }
        for (CustomBlock b : rotating.values()) {
            JsonObject variants = new JsonObject();
            for (String facing : CustomBlock.FACINGS) variants.add("facing=" + facing, variant(b.modelRef(), glazedRotation(facing)));
            out.put("assets/minecraft/blockstates/" + b.blockId() + ".json", json(wrap(variants)));
        }
    }

    /** Vanilla glazed terracotta rotation per facing (south is the unrotated orientation). */
    static int glazedRotation(String facing) {
        return switch (facing) {
            case "south" -> 0;
            case "west" -> 90;
            case "north" -> 180;
            case "east" -> 270;
            default -> 0;
        };
    }

    private static JsonObject variant(String model, int y) {
        JsonObject v = new JsonObject();
        v.addProperty("model", model);
        if (y != 0) v.addProperty("y", y);
        return v;
    }

    private static JsonObject wrap(JsonObject variants) {
        JsonObject o = new JsonObject();
        o.add("variants", variants);
        return o;
    }

    // ------------------------------------------------------------------ validation

    private static void validate(Map<String, byte[]> files, List<PackIssue> issues) {
        for (Map.Entry<String, byte[]> e : files.entrySet()) {
            String path = e.getKey();
            if (path.endsWith(".json") || path.endsWith(".mcmeta")) {
                JsonElement el;
                try {
                    el = JsonParser.parseString(new String(e.getValue(), StandardCharsets.UTF_8));
                } catch (RuntimeException ex) {
                    issues.add(new PackIssue(true, path, "invalid JSON: " + ex.getMessage()));
                    continue;
                }
                if (path.contains("/models/") && el.isJsonObject()) checkModelRefs(path, el.getAsJsonObject(), files, issues);
                if (path.contains("/blockstates/") && el.isJsonObject()) checkBlockstateRefs(path, el.getAsJsonObject(), files, issues);
            } else if (path.endsWith(".png")) {
                try {
                    BufferedImage img = ImageIO.read(new ByteArrayInputStream(e.getValue()));
                    if (img == null) {
                        issues.add(new PackIssue(true, path, "not a readable PNG"));
                    } else if (path.contains("/textures/block/") || path.contains("/textures/item/")) {
                        boolean animated = files.containsKey(path + ".mcmeta");
                        if (!animated && img.getWidth() != img.getHeight()) {
                            issues.add(new PackIssue(true, path, "must be square (" + img.getWidth() + "x" + img.getHeight()
                                    + "); animated textures need a .png.mcmeta"));
                        } else if (animated && img.getHeight() % img.getWidth() != 0) {
                            issues.add(new PackIssue(true, path, "animation strip height must be a multiple of its width"));
                        } else if (img.getWidth() > 512) {
                            issues.add(new PackIssue(false, path, "very large texture (" + img.getWidth() + "px)"));
                        }
                    }
                } catch (IOException ex) {
                    issues.add(new PackIssue(true, path, "unreadable image: " + ex.getMessage()));
                }
            }
        }
    }

    private static void checkModelRefs(String path, JsonObject model, Map<String, byte[]> files, List<PackIssue> issues) {
        if (model.has("parent")) checkRef(path, model.get("parent").getAsString(), "models", ".json", files, issues);
        if (model.has("textures") && model.get("textures").isJsonObject()) {
            for (Map.Entry<String, JsonElement> t : model.getAsJsonObject("textures").entrySet()) {
                String ref = t.getValue().getAsString();
                if (!ref.startsWith("#")) checkRef(path, ref, "textures", ".png", files, issues);
            }
        }
    }

    private static void checkBlockstateRefs(String path, JsonObject state, Map<String, byte[]> files, List<PackIssue> issues) {
        if (!state.has("variants")) return;
        for (Map.Entry<String, JsonElement> v : state.getAsJsonObject("variants").entrySet()) {
            List<JsonElement> options = new ArrayList<>();
            if (v.getValue().isJsonArray()) v.getValue().getAsJsonArray().forEach(options::add);
            else options.add(v.getValue());
            for (JsonElement o : options) {
                if (o.isJsonObject() && o.getAsJsonObject().has("model")) {
                    checkRef(path, o.getAsJsonObject().get("model").getAsString(), "models", ".json", files, issues);
                }
            }
        }
    }

    /** Non-minecraft references must exist in the pack; vanilla ones are assumed to exist in the client. */
    private static void checkRef(String from, String ref, String kind, String ext, Map<String, byte[]> files, List<PackIssue> issues) {
        String ns = ref.contains(":") ? ref.substring(0, ref.indexOf(':')) : "minecraft";
        String name = ref.contains(":") ? ref.substring(ref.indexOf(':') + 1) : ref;
        String target = "assets/" + ns + "/" + kind + "/" + name + ext;
        if (ns.equals("minecraft") && !files.containsKey(target)) return;
        if (!files.containsKey(target)) issues.add(new PackIssue(true, from, "references missing " + kind + " '" + ref + "' (" + target + ")"));
    }

