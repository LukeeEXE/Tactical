    private JsonObject packMeta() {
        JsonObject pack = new JsonObject();
        pack.addProperty("description", description);
        com.google.gson.JsonArray v = new com.google.gson.JsonArray();
        v.add(formatMajor);
        v.add(formatMinor);
        pack.add("min_format", v);
        pack.add("max_format", v.deepCopy());
        JsonObject o = new JsonObject();
        o.add("pack", pack);
        return o;
    }

    private static void readTree(Path dir, String prefix, Map<String, byte[]> out) throws IOException {
        if (!Files.isDirectory(dir)) return;
        try (Stream<Path> s = Files.walk(dir)) {
            for (Path p : s.filter(Files::isRegularFile).sorted().toList()) {
                String rel = dir.relativize(p).toString().replace('\\', '/');
                if (rel.startsWith(".") || rel.contains("/.")) continue; // skip hidden files (.DS_Store etc.)
                out.put(prefix + rel, Files.readAllBytes(p));
            }
        }
    }

    private static byte[] json(JsonElement e) {
        return GSON.toJson(e).getBytes(StandardCharsets.UTF_8);
    }

    static byte[] transparentPng(int w, int h) {
        try {
            BufferedImage img = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            ImageIO.write(img, "png", out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private static byte[] zip(Map<String, byte[]> files) throws IOException {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        try (ZipOutputStream zip = new ZipOutputStream(bytes)) {
            for (Map.Entry<String, byte[]> e : files.entrySet()) {
                ZipEntry entry = new ZipEntry(e.getKey());
                entry.setTime(FIXED_TIME);
                zip.putNextEntry(entry);
                zip.write(e.getValue());
                zip.closeEntry();
            }
        }
        return bytes.toByteArray();
    }

    static String sha1(byte[] data) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-1").digest(data));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
