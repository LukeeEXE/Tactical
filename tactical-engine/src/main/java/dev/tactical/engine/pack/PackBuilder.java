package dev.tactical.engine.pack;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/**
 * Builds the server resource pack from (lowest to highest precedence):
 * <ol>
 *   <li>generated files (pack.mcmeta, transparent Hunger-variant food sprites, custom-block blockstates and models)</li>
 *   <li>{@code resourcepack/assets/**} (admin art and vanilla overrides)</li>
 *   <li>{@code resourcepack/overrides/**} (copied verbatim)</li>
 * </ol>
 * Files the HUD depends on are protected: an admin file at such a path is rejected with an explanation.
 * Output is a deterministic zip (sorted entries, fixed timestamps), so an unchanged pack keeps its SHA-1 and
 * clients do not re-download it.
 */
public final class PackBuilder {

    /** Paths generated by the plugin that admin files may not replace (the HUD relies on them). */
    public static final Set<String> PROTECTED = Set.of(
            "assets/minecraft/textures/gui/sprites/hud/food_empty_hunger.png",
            "assets/minecraft/textures/gui/sprites/hud/food_half_hunger.png",
            "assets/minecraft/textures/gui/sprites/hud/food_full_hunger.png");

    private static final Gson GSON = new GsonBuilder().disableHtmlEscaping().create();
    private static final long FIXED_TIME = 315532800000L; // 1980-01-01, zip epoch

    public record Result(byte[] zip, String sha1, List<PackIssue> issues, Map<String, Integer> stats) {
        public boolean hasErrors() {
            return issues.stream().anyMatch(PackIssue::error);
        }
    }

    private final int formatMajor;
    private final int formatMinor;
    private final String description;

    public PackBuilder(int formatMajor, int formatMinor, String description) {
        this.formatMajor = formatMajor;
        this.formatMinor = formatMinor;
        this.description = description;
    }

    /**
     * @param sourceRoot   {@code plugins/Tactical/resourcepack} (may not exist)
     * @param blocks       parsed custom blocks
     * @param knownBlocks  block ids that exist on this server version (for state validation)
     */
    public Result build(Path sourceRoot, List<CustomBlock> blocks, Set<String> knownBlocks) throws IOException {
        List<PackIssue> issues = new ArrayList<>();
        Map<String, byte[]> files = new TreeMap<>();
        Map<String, Integer> stats = new LinkedHashMap<>();

        // 1. generated
        files.put("pack.mcmeta", json(packMeta()));
        byte[] clear = transparentPng(9, 9);
        for (String p : PROTECTED) files.put(p, clear);
        generateConstructionBlock(files);
        Map<String, byte[]> user = new TreeMap<>();
        readTree(sourceRoot.resolve("assets"), "assets/", user);
        generateBlocks(blocks, knownBlocks, user, files, issues);
        stats.put("custom_blocks", blocks.size());

        // 2. admin assets, 3. verbatim overrides
        Map<String, byte[]> overrides = new TreeMap<>();
        readTree(sourceRoot.resolve("overrides"), "", overrides);
        int replaced = 0;
        for (Map<String, byte[]> layer : List.of(user, overrides)) {
            for (Map.Entry<String, byte[]> e : layer.entrySet()) {
                String path = e.getKey();
                if (PROTECTED.contains(path)) {
                    issues.add(new PackIssue(true, path, "this sprite is generated transparent so the hunger bar is hidden; "
                            + "your file was ignored"));
                    continue;
                }
                if (files.containsKey(path) && !path.equals("pack.mcmeta") && !path.equals(CONSTRUCTION_TEXTURE)) {
                    replaced++;
                    issues.add(new PackIssue(false, path, "your file replaces a generated file"));
                }
                files.put(path, e.getValue());
            }
        }
        stats.put("admin_files", user.size() + overrides.size());
        stats.put("replaced_generated", replaced);
        validate(files, issues);
        stats.put("files", files.size());

        byte[] zip = zip(files);
        return new Result(zip, sha1(zip), issues, stats);
    }

    // ------------------------------------------------------------------ construction block

    /** Texture admins replace to restyle construction blocks (resourcepack/assets/tactical/textures/block/construction_block.png). */
    public static final String CONSTRUCTION_TEXTURE = "assets/tactical/textures/block/construction_block.png";

    /**
     * Construction blocks are vanilla infested stone (used for nothing else in this game). Overriding its block model
     * retextures both the placed block and the item, since the item definition points at the same model.
     * A placeholder texture is generated; an admin texture at {@link #CONSTRUCTION_TEXTURE} replaces it.
     */
    private static void generateConstructionBlock(Map<String, byte[]> files) {
        JsonObject model = new JsonObject();
        model.addProperty("parent", "minecraft:block/cube_all");
        JsonObject textures = new JsonObject();
        textures.addProperty("all", "tactical:block/construction_block");
        model.add("textures", textures);
        files.put("assets/minecraft/models/block/infested_stone.json", json(model));
        files.put(CONSTRUCTION_TEXTURE, placeholderConstructionTexture());
    }

    /** 16x16 diagonal hazard stripes, so placeholder construction blocks are obviously not map geometry. */
    static byte[] placeholderConstructionTexture() {
        try {
            BufferedImage img = new BufferedImage(16, 16, BufferedImage.TYPE_INT_ARGB);
            for (int x = 0; x < 16; x++) {
                for (int y = 0; y < 16; y++) {
                    boolean stripe = ((x + y) / 4) % 2 == 0;
                    boolean edge = x == 0 || y == 0 || x == 15 || y == 15;
                    int rgb = edge ? 0x3A3A3A : stripe ? 0xE0A020 : 0x5A5A5A;
                    img.setRGB(x, y, 0xFF000000 | rgb);
                }
            }
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            ImageIO.write(img, "png", out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
    }

    // ------------------------------------------------------------------ custom blocks

    private void generateBlocks(List<CustomBlock> blocks, Set<String> knownBlocks, Map<String, byte[]> user,
                                Map<String, byte[]> out, List<PackIssue> issues) {
        Map<String, CustomBlock> claimed = new LinkedHashMap<>();
        Map<String, Map<String, CustomBlock>> glazed = new TreeMap<>();
        Map<String, CustomBlock> rotating = new TreeMap<>();
        Map<String, CustomBlock> slabs = new TreeMap<>();
        for (CustomBlock b : blocks) {
            String where = "blocks/" + b.id();
            if (!knownBlocks.contains(b.blockId())) {
                issues.add(new PackIssue(true, where, "minecraft:" + b.blockId() + " does not exist on this server version"));
                continue;
            }
            CustomBlock other = claimed.putIfAbsent(b.stateKey(), b);
            if (other != null) {
                issues.add(new PackIssue(true, where, "state " + b.stateKey() + " is already used by '" + other.id() + "'"));
                continue;
            }
            if (b.kind() == CustomBlock.Kind.GLAZED_ROTATING && glazed.containsKey(b.blockId())
                    || b.kind() == CustomBlock.Kind.GLAZED_FACING && rotating.containsKey(b.blockId())) {
                issues.add(new PackIssue(true, where, b.blockId() + " cannot mix a rotating replacement with per-facing blocks"));
                continue;
            }
            // model
            if (b.model() != null) {
                String path = "assets/tactical/models/" + b.model();
                if (!user.containsKey(path)) {
                    issues.add(new PackIssue(true, where, "model file not found: resourcepack/" + path));
                    continue;
                }
                if (!b.model().equals("block/" + b.id() + ".json")) {
                    // copy under the canonical name so the blockstate can reference tactical:block/<id>
                    out.put("assets/tactical/models/block/" + b.id() + ".json", user.get(path));
                }
            } else {
                String tex = "assets/tactical/textures/" + b.texture();
                if (!user.containsKey(tex)) {
                    issues.add(new PackIssue(true, where, "texture not found: resourcepack/" + tex));
                    continue;
                }
                String texRef = "tactical:" + b.texture().substring(0, b.texture().length() - 4);
                JsonObject model = new JsonObject();
                JsonObject textures = new JsonObject();
                if (b.kind() == CustomBlock.Kind.GLAZED_ROTATING) {
                    model.addProperty("parent", "minecraft:block/template_glazed_terracotta");
                    textures.addProperty("pattern", texRef);
                } else {
                    model.addProperty("parent", "minecraft:block/cube_all");
                    textures.addProperty("all", texRef);
                }
                model.add("textures", textures);
                out.put("assets/tactical/models/block/" + b.id() + ".json", json(model));
            }
            switch (b.kind()) {
                case DOUBLE_SLAB -> slabs.put(b.blockId(), b);
                case GLAZED_FACING -> glazed.computeIfAbsent(b.blockId(), k -> new TreeMap<>()).put(b.facing(), b);
                case GLAZED_ROTATING -> rotating.put(b.blockId(), b);
            }
        }
        for (CustomBlock b : slabs.values()) {
            JsonObject variants = new JsonObject();
            variants.add("type=bottom", variant(SlabModels.bottom(b.blockId()), 0));
            variants.add("type=top", variant(SlabModels.top(b.blockId()), 0));
            variants.add("type=double", variant(b.modelRef(), 0));
            out.put("assets/minecraft/blockstates/" + b.blockId() + ".json", json(wrap(variants)));
        }
        for (Map.Entry<String, Map<String, CustomBlock>> e : glazed.entrySet()) {
            JsonObject variants = new JsonObject();
            String vanilla = "minecraft:block/" + e.getKey();
            for (String facing : CustomBlock.FACINGS) {
                CustomBlock b = e.getValue().get(facing);
                variants.add("facing=" + facing, b != null ? variant(b.modelRef(), 0) : variant(vanilla, glazedRotation(facing)));
            }
            out.put("assets/minecraft/blockstates/" + e.getKey() + ".json", json(wrap(variants)));
        }
        for (CustomBlock b : rotating.values()) {
            JsonObject variants = new JsonObject();
            for (String facing : CustomBlock.FACINGS) variants.add("facing=" + facing, variant(b.modelRef(), glazedRotation(facing)));
            out.put("assets/minecraft/blockstates/" + b.blockId() + ".json", json(wrap(variants)));
        }
    }

    /** Vanilla glazed terracotta rotation per facing (south is the unrotated orientation). */
    static int glazedRotation(String facing) {
        return switch (facing) {
            case "south" -> 0;
            case "west" -> 90;
            case "north" -> 180;
            case "east" -> 270;
            default -> 0;
        };
    }

    private static JsonObject variant(String model, int y) {
        JsonObject v = new JsonObject();
        v.addProperty("model", model);
        if (y != 0) v.addProperty("y", y);
        return v;
    }

    private static JsonObject wrap(JsonObject variants) {
        JsonObject o = new JsonObject();
        o.add("variants", variants);
        return o;
    }

    // ------------------------------------------------------------------ validation

    private static void validate(Map<String, byte[]> files, List<PackIssue> issues) {
        for (Map.Entry<String, byte[]> e : files.entrySet()) {
            String path = e.getKey();
            if (path.endsWith(".json") || path.endsWith(".mcmeta")) {
                JsonElement el;
                try {
                    el = JsonParser.parseString(new String(e.getValue(), StandardCharsets.UTF_8));
                } catch (RuntimeException ex) {
                    issues.add(new PackIssue(true, path, "invalid JSON: " + ex.getMessage()));
                    continue;
                }
                if (path.contains("/models/") && el.isJsonObject()) checkModelRefs(path, el.getAsJsonObject(), files, issues);
                if (path.contains("/blockstates/") && el.isJsonObject()) checkBlockstateRefs(path, el.getAsJsonObject(), files, issues);
            } else if (path.endsWith(".png")) {
                try {
                    BufferedImage img = ImageIO.read(new ByteArrayInputStream(e.getValue()));
                    if (img == null) {
                        issues.add(new PackIssue(true, path, "not a readable PNG"));
                    } else if (path.contains("/textures/block/") || path.contains("/textures/item/")) {
                        boolean animated = files.containsKey(path + ".mcmeta");
                        if (!animated && img.getWidth() != img.getHeight()) {
                            issues.add(new PackIssue(true, path, "must be square (" + img.getWidth() + "x" + img.getHeight()
                                    + "); animated textures need a .png.mcmeta"));
                        } else if (animated && img.getHeight() % img.getWidth() != 0) {
                            issues.add(new PackIssue(true, path, "animation strip height must be a multiple of its width"));
                        } else if (img.getWidth() > 512) {
                            issues.add(new PackIssue(false, path, "very large texture (" + img.getWidth() + "px)"));
                        }
                    }
                } catch (IOException ex) {
                    issues.add(new PackIssue(true, path, "unreadable image: " + ex.getMessage()));
                }
            }
        }
    }

    private static void checkModelRefs(String path, JsonObject model, Map<String, byte[]> files, List<PackIssue> issues) {
        if (model.has("parent")) checkRef(path, model.get("parent").getAsString(), "models", ".json", files, issues);
        if (model.has("textures") && model.get("textures").isJsonObject()) {
            for (Map.Entry<String, JsonElement> t : model.getAsJsonObject("textures").entrySet()) {
                String ref = t.getValue().getAsString();
                if (!ref.startsWith("#")) checkRef(path, ref, "textures", ".png", files, issues);
            }
        }
    }

    private static void checkBlockstateRefs(String path, JsonObject state, Map<String, byte[]> files, List<PackIssue> issues) {
        if (!state.has("variants")) return;
        for (Map.Entry<String, JsonElement> v : state.getAsJsonObject("variants").entrySet()) {
            List<JsonElement> options = new ArrayList<>();
            if (v.getValue().isJsonArray()) v.getValue().getAsJsonArray().forEach(options::add);
            else options.add(v.getValue());
            for (JsonElement o : options) {
                if (o.isJsonObject() && o.getAsJsonObject().has("model")) {
                    checkRef(path, o.getAsJsonObject().get("model").getAsString(), "models", ".json", files, issues);
                }
            }
        }
    }

    /** Non-minecraft references must exist in the pack; vanilla ones are assumed to exist in the client. */
    private static void checkRef(String from, String ref, String kind, String ext, Map<String, byte[]> files, List<PackIssue> issues) {
        String ns = ref.contains(":") ? ref.substring(0, ref.indexOf(':')) : "minecraft";
        String name = ref.contains(":") ? ref.substring(ref.indexOf(':') + 1) : ref;
        String target = "assets/" + ns + "/" + kind + "/" + name + ext;
        if (ns.equals("minecraft") && !files.containsKey(target)) return;
        if (!files.containsKey(target)) issues.add(new PackIssue(true, from, "references missing " + kind + " '" + ref + "' (" + target + ")"));
    }

    // ------------------------------------------------------------------ helpers

    private JsonObject packMeta() {
        JsonObject pack = new JsonObject();
        pack.addProperty("description", description);
        com.google.gson.JsonArray v = new com.google.gson.JsonArray();
        v.add(formatMajor);
        v.add(formatMinor);
        pack.add("min_format", v);
        pack.add("max_format", v.deepCopy());
        JsonObject o = new JsonObject();
        o.add("pack", pack);
        return o;
    }

    private static void readTree(Path dir, String prefix, Map<String, byte[]> out) throws IOException {
        if (!Files.isDirectory(dir)) return;
        try (Stream<Path> s = Files.walk(dir)) {
            for (Path p : s.filter(Files::isRegularFile).sorted().toList()) {
                String rel = dir.relativize(p).toString().replace('\\', '/');
                if (rel.startsWith(".") || rel.contains("/.")) continue; // skip hidden files (.DS_Store etc.)
                out.put(prefix + rel, Files.readAllBytes(p));
            }
        }
    }

    private static byte[] json(JsonElement e) {
        return GSON.toJson(e).getBytes(StandardCharsets.UTF_8);
    }

    static byte[] transparentPng(int w, int h) {
        try {
            BufferedImage img = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            ImageIO.write(img, "png", out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private static byte[] zip(Map<String, byte[]> files) throws IOException {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        try (ZipOutputStream zip = new ZipOutputStream(bytes)) {
            for (Map.Entry<String, byte[]> e : files.entrySet()) {
                ZipEntry entry = new ZipEntry(e.getKey());
                entry.setTime(FIXED_TIME);
                zip.putNextEntry(entry);
                zip.write(e.getValue());
                zip.closeEntry();
            }
        }
        return bytes.toByteArray();
    }

    static String sha1(byte[] data) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-1").digest(data));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
